const BY_TOPIC = new Map(FALLBACKS.map((f) => [f.topicId, f]));

/** 某条主题有没有通用兜底；没有就返回 undefined（UI 那边照旧只显示「去要文件」） */
export function fallbackFor(topicId: string): FallbackNote | undefined {
  return BY_TOPIC.get(topicId);
}

export const FALLBACK_COUNT = FALLBACKS.length;

/**
 * 一批缺口里，有多少条能先用通用口径顶着、多少条是真空白。
 * 传进来的只要带 topic.id 就行（KnowledgeGap 天然满足），不反向依赖 gaps.ts。
 */
export function coverageWithFallback(gaps: readonly { topic: { id: string } }[]): {
  withFallback: number;
  bare: number;
} {
  let withFallback = 0;
  for (const g of gaps) if (BY_TOPIC.has(g.topic.id)) withFallback++;
  return { withFallback, bare: gaps.length - withFallback };
}
