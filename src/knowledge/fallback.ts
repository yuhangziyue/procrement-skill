// 通用兜底知识：知识库里还没有公司文档的那些主题，先给一份「行业通用口径」顶着。
//
// 为什么要有这个文件：
//   taxonomy 定了 40 条该有的主题，gaps 会告诉你缺哪条、去找谁要。但在公司文档补齐之前，
//   只会催人要文件的提醒是没用的——她今天就要下单，不能等一份《请购管理流程》从主管手里流出来。
//   所以每条主题都先给一份通用版：行业里普遍这么做、这么算、这么防坑。
//
// 三条写作纪律：
//   1) 不编具体数字。账期天数、审批额度、抽检比例、超收上限这类各家不同的，一律不写死，
//      挪进 companyVaries，并写清「去问谁、要哪份文件」。唯一写死的数字是有公开依据的
//      （如国内货物增值税一般计税 13%），且仍在 companyVaries 里提示核对适用税率。
//   2) U8 菜单路径一律带「⚠️ 待实机核对」——本项目从未在真机上验证过菜单，
//      写得越确定，用户照着点不到时越怀疑整套知识。
//   3) companyVaries 是这份兜底的诚实边界，不是免责声明。它必须给出下一步动作，
//      所以每条里都得有「问 / 要 / 找」这样的具体动作词（测试会拦）。
//
// 内容主要摘写自 ~/.claude/skills/procurement/knowledge-base/01~05（采购技能树 + U8 基础 + 三份 SOP），
// 权威出处挂在 sourceIds 上（指向 src/tutorial/sources.ts），能直接上手操作的挂 tutorialIds。

