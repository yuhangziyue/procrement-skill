// 素材把每条菜单路径 / 每个结论标了可信度：
//   ✅ 多来源确认      → confidence: "verified"
//   ⚠️ 单来源，待实机核对 → confidence: "unverified"
//   ❌ 未检索到        → confidence: "unknown"（这类绝不能编路径，where 留空）
//
// 本文件严格照抄素材的标注，一条不升级、不抹掉。哪一步标了 ❌／unknown，
// 就必须能在 OPEN_QUESTIONS 里找到对应的核对条目。
//
// 整篇 Tutorial.confidence 不是手写的，是 tutorial() 按"各步最低"自动算出来的，
// 避免手改步骤时忘记同步整篇的可信度。

export type Confidence = "verified" | "unverified" | "unknown"; // ✅ / ⚠️ / ❌

export interface TutorialStep {
  n: number;
  title: string;
  detail: string;
  /** 菜单路径。没有可靠路径的（confidence: unknown）一律不填，不编造。 */
  where?: string;
  confidence: Confidence;
  /** 图位说明：该截什么图、红框标什么。 */
  shot?: string;
  /** 这一步常见的坑（如果有）。 */
  pitfall?: string;
}

export interface Tutorial {
  id: string;
  title: string;
  goal: string;
  scene: string;
  freq: "每天" | "每周" | "每月" | "按需";
  category: "query" | "export" | "import" | "flow";
  minutes: number;
  confidence: Confidence;
  steps: TutorialStep[];
  checkpoints: string[];
  troubleshooting: { symptom: string; cause: string; fix: string }[];
  related?: string[];
}

// ---- 内部小工具：自动编号 + 自动算整篇可信度（= 各步最低），不手写、不会漂移 ----

const RANK: Record<Confidence, number> = { unknown: 0, unverified: 1, verified: 2 };
const BY_RANK: Confidence[] = ["unknown", "unverified", "verified"];

function numbered(steps: Array<Omit<TutorialStep, "n">>): TutorialStep[] {
  return steps.map((s, i) => ({ ...s, n: i + 1 }));
}

function overallConfidence(steps: TutorialStep[]): Confidence {
  const worst = steps.reduce((m, s) => Math.min(m, RANK[s.confidence]), 2);
  return BY_RANK[worst];
}

function tutorial(
  t: Omit<Tutorial, "confidence" | "steps"> & { steps: Array<Omit<TutorialStep, "n">> },
): Tutorial {
  const steps = numbered(t.steps);
  return { ...t, steps, confidence: overallConfidence(steps) };
}

